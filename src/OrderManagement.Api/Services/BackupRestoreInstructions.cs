namespace OrderManagement.Api.Services;

public static class BackupRestoreInstructions
{
    public const string FileName = "KAK_VOSSTANOVIT.txt";

    public static string Build(
        string businessName,
        DateTime createdUtc,
        string archiveFileName,
        string? hostBackupFolderHint)
    {
        var createdLocal = createdUtc.ToLocalTime().ToString("dd.MM.yyyy HH:mm");
        var folderHint = string.IsNullOrWhiteSpace(hostBackupFolderHint)
            ? "папка backups в каталоге проекта (см. docker-compose.yml)"
            : hostBackupFolderHint.Trim();

        return $"""
            ═══════════════════════════════════════════════════════════════════
              КАК ВОССТАНОВИТЬ ПРОГРАММУ «УПРАВЛЕНИЕ ЗАКАЗАМИ»
              (Order Management) — ПРОСТАЯ ИНСТРУКЦИЯ
            ═══════════════════════════════════════════════════════════════════

            Этот файл лежит внутри архива резервной копии:
              {archiveFileName}

            Бизнес: {businessName}
            Когда сделана копия: {createdLocal}

            ───────────────────────────────────────────────────────────────────
            ЧТО ВНУТРИ АРХИВА
            ───────────────────────────────────────────────────────────────────

            1) database.sql  — вся база данных (заказы, клиенты, склад, документы)
            2) uploads/      — файлы: PDF накладных, логотипы, картинки товаров
            3) manifest.json — техническое описание копии
            4) этот файл     — инструкция по восстановлению

            ───────────────────────────────────────────────────────────────────
            КОГДА НУЖНО ВОССТАНОВЛЕНИЕ
            ───────────────────────────────────────────────────────────────────

            • Программа не запускается после сбоя компьютера
            • База данных повреждена или «пустая»
            • Пропали PDF-файлы или картинки
            • Вы переезжаете на новый компьютер

            ───────────────────────────────────────────────────────────────────
            ЧТО НУЖНО ЗАРАНЕЕ
            ───────────────────────────────────────────────────────────────────

            ✓ Установлен Docker Desktop (Windows) или Docker (Linux/Mac)
            ✓ Есть исходный код проекта (папка с docker-compose.yml)
            ✓ Есть этот ZIP-архив резервной копии
            ✓ 15–30 минут времени

            ───────────────────────────────────────────────────────────────────
            ШАГ 1. ОСТАНОВИТЬ ПРОГРАММУ
            ───────────────────────────────────────────────────────────────────

            Откройте терминал (PowerShell) в папке проекта и выполните:

              docker compose down

            Это безопасно останавливает контейнеры. Ваши данные в Docker-томах
            пока остаются на диске.

            ───────────────────────────────────────────────────────────────────
            ШАГ 2. РАСПАКОВАТЬ АРХИВ
            ───────────────────────────────────────────────────────────────────

            Распакуйте ZIP в любую временную папку, например:

              C:\\Temp\\restore-ordermgmt\\

            Внутри должны быть файлы database.sql и папка uploads.

            ───────────────────────────────────────────────────────────────────
            ШАГ 3. ВОССТАНОВИТЬ БАЗУ ДАННЫХ
            ───────────────────────────────────────────────────────────────────

            3.1. Запустите только базу данных:

              docker compose up -d db

            Подождите 10–20 секунд, пока PostgreSQL запустится.

            3.2. Скопируйте database.sql в контейнер базы:

              docker cp "C:\\Temp\\restore-ordermgmt\\database.sql" ordermgmt-db:/tmp/database.sql

              (замените путь на свой)

            3.3. Пересоздайте базу и загрузите данные:

              docker exec -i ordermgmt-db psql -U ordermgmt -d postgres -c "DROP DATABASE IF EXISTS ordermgmt;"
              docker exec -i ordermgmt-db psql -U ordermgmt -d postgres -c "CREATE DATABASE ordermgmt;"
              docker exec -i ordermgmt-db psql -U ordermgmt -d ordermgmt -f /tmp/database.sql

            Если команды прошли без ERROR — база восстановлена.

            ───────────────────────────────────────────────────────────────────
            ШАГ 4. ВОССТАНОВИТЬ ФАЙЛЫ (PDF, КАРТИНКИ)
            ───────────────────────────────────────────────────────────────────

            4.1. Остановите API (если запущен):

              docker compose stop api

            4.2. Скопируйте папку uploads из распакованного архива в том Docker.
            Самый простой способ — через временный контейнер:

              docker run --rm -v ordermgmt_uploads:/dest -v "C:\\Temp\\restore-ordermgmt\\uploads:/src" alpine sh -c "rm -rf /dest/* && cp -a /src/. /dest/"

              (замените путь C:\\Temp\\restore-ordermgmt\\uploads на свой)

            ───────────────────────────────────────────────────────────────────
            ШАГ 5. ЗАПУСТИТЬ ПРОГРАММУ СНОВА
            ───────────────────────────────────────────────────────────────────

              docker compose up -d

            Откройте браузер: http://localhost:5173 (или адрес, который вы используете)

            Войдите под своим email и паролем — данные должны быть на месте.

            ───────────────────────────────────────────────────────────────────
            ГДЕ ХРАНЯТСЯ РЕЗЕРВНЫЕ КОПИИ НА ДИСКЕ
            ───────────────────────────────────────────────────────────────────

            При работе через Docker копии сохраняются в папку на вашем компьютере:

              {folderHint}

            Рекомендуется дополнительно копировать ZIP на внешний диск или в облако.

            ───────────────────────────────────────────────────────────────────
            ЕСЛИ ЧТО-ТО НЕ ПОЛУЧИЛОСЬ
            ───────────────────────────────────────────────────────────────────

            • Прочитайте текст ошибки в терминале — часто там написано, чего не хватает
            • Убедитесь, что Docker Desktop запущен (иконка в трее)
            • Проверьте, что архив распакован полностью и database.sql не пустой
            • Не удаляйте старый архив, пока не убедитесь, что восстановление прошло успешно

            ───────────────────────────────────────────────────────────────────
            ВАЖНО
            ───────────────────────────────────────────────────────────────────

            • Делайте резервную копию регулярно (раз в неделю или перед важными изменениями)
            • Храните минимум 2–3 последние копии в разных местах
            • Пароль от входа в программу в архив НЕ входит — запомните его отдельно

            ═══════════════════════════════════════════════════════════════════
            """;
    }
}
